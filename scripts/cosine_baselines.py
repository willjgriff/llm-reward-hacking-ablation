"""Baselines for cosine similarities between directions (laptop, CPU).

A cosine between two hack directions only means something next to what
unrelated directions give. Baselines here:
  1. random isotropic unit vectors in d = 5120 (analytic: (cos + 1) / 2 ~
     Beta((d-1)/2, (d-1)/2); RMS 1/sqrt(d), E|cos| ~ sqrt(2/(pi d))), plus the
     max over 64 layers, which is what "max (L)" columns report;
  2. the stored random control directions (X0 / P1 / P2 recipe);
  3. activation-based unrelated directions, which inherit the residual stream's
     anisotropy that random vectors lack: environment identity (difference of
     the non-hack class means of two environments) and the stage-8 concept
     direction (covert vs simple, no hacking data);
  4. same-behaviour floors: a direction against itself re-extracted from a
     random half (H1) or from 25 / 100 rows per class (N25, N100).
Pooled directions are means of member unit vectors, so cos(pool, member) =
sqrt((1 + c) / 2) with c = cos(members): ~0.71 by construction at c = 0.

Spanish/French and refusal directions need forward passes (GPU) and are not here.

  uv run scripts/cosine_baselines.py [--data-root data] [--out data/analysis/cosine_baselines]
"""
from __future__ import annotations

import argparse
import itertools
import json
from pathlib import Path

import numpy as np
from safetensors.numpy import load_file
from scipy import stats

D = 5120
LAYERS = [20, 30, 40, 48, 56, 63]
WINDOW = range(40, 64)  # decoder layers the stacked edit touches (rows 40..63)


def unit(x: np.ndarray) -> np.ndarray:
    n = np.linalg.norm(x, axis=-1, keepdims=True)
    return np.where(n > 0, x / np.where(n > 0, n, 1), 0)


def analytic() -> dict:
    a = (D - 1) / 2
    beta = stats.beta(a, a)
    q = lambda p: 2 * beta.ppf(0.5 + p / 2) - 1  # noqa: E731  quantile of |cos|
    # max over 64 independent layers of |cos|: P(max <= x) = P(|cos| <= x)^64
    qmax = lambda p: 2 * beta.ppf(0.5 + p ** (1 / 64) / 2) - 1  # noqa: E731
    return {
        "rms": 1 / np.sqrt(D),
        "mean_abs": float(np.sqrt(2 / (np.pi * D))),
        "abs_q95": float(q(0.95)),
        "abs_q99": float(q(0.99)),
        "abs_q999": float(q(0.999)),
        "max64_abs_median": float(qmax(0.5)),
        "max64_abs_q95": float(qmax(0.95)),
        "window24_mean_sd": float(1 / np.sqrt(D) / np.sqrt(24)),
    }


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--data-root", default="data")
    ap.add_argument("--out", default="data/analysis/cosine_baselines")
    args = ap.parse_args()
    root = Path(args.data_root)
    out = Path(args.out)
    out.mkdir(parents=True, exist_ok=True)

    s4 = root / "stage4"
    paths = {
        "D_TV": s4 / "stage7/s7-tv/directions/tamper_vs_clean__cot_last.safetensors",
        "D_MBPP": s4 / "stage7/s7-mbpp/directions/hack_vs_clean__cot_last.safetensors",
        "D_GR": s4 / "stage7/s7-gr/directions/cheat_vs_noncheat__cot_last.safetensors",
        "R1 (attempt_vs_A, completion_last)": s4 / "tv27b-full/directions/attempt_vs_A__completion_last.safetensors",
        "concept (covert vs simple)": s4 / "stage8/s8-concept/directions/covert_vs_simple__cot_last.safetensors",
        "random_s1": root / "stage8/stage8/directions/random_s1.safetensors",
        "random_s2": root / "stage8/stage8/directions/random_s2.safetensors",
        "D_MBPP+GR (X2)": root / "stage7/stage7/directions/pooled/D_MBPP+GR__cot_last.safetensors",
    }
    floors = {
        "D_TV": {"n25": "stage7/s7-tv-n25", "n50": "stage7/s7-tv-n50", "n100": "stage7/s7-tv-n100"},
        "D_GR": {"H1": "stage8/s8-gr-H1", "N25": "stage8/s8-gr-N25", "N100": "stage8/s8-gr-N100", "stage8 full": "stage8/s8-gr-full"},
        "D_MBPP": {"H1": "stage8/s8-mbpp-H1", "N25": "stage8/s8-mbpp-N25", "N100": "stage8/s8-mbpp-N100", "stage8 full": "stage8/s8-mbpp-full"},
    }
    fname = {"D_TV": "tamper_vs_clean", "D_GR": "cheat_vs_noncheat", "D_MBPP": "hack_vs_clean"}
    raw = {k: load_file(str(p)) for k, p in paths.items()}
    U = {k: unit(v["direction"].astype(np.float64)) for k, v in raw.items()}

    # activation-based unrelated directions: environment identity from non-hack means
    neg = {e: raw[e]["mean_neg"].astype(np.float64) for e in ["D_TV", "D_MBPP", "D_GR"]}
    U["env: TV − MBPP (non-hack means)"] = unit(neg["D_TV"] - neg["D_MBPP"])
    U["env: TV − GR (non-hack means)"] = unit(neg["D_TV"] - neg["D_GR"])
    U["env: MBPP − GR (non-hack means)"] = unit(neg["D_MBPP"] - neg["D_GR"])
    allmean = (neg["D_TV"] + neg["D_MBPP"] + neg["D_GR"]) / 3
    U["mean residual (anisotropy axis)"] = unit(allmean)

    def cos(a, b):
        return (U[a] * U[b]).sum(-1)

    an = analytic()
    lines = ["# Cosine baselines for direction comparisons", "", "Generated by `scripts/cosine_baselines.py`. Directions: per-layer unit rows, `cot_last` unless named; index = `output_hidden_states` (0 = embeddings).", ""]
    lines += [
        "## 1. Random isotropic vectors, d = 5120 (analytic)",
        "",
        f"- |cos| RMS (= SD of cos) **{an['rms']:.4f}**, mean |cos| **{an['mean_abs']:.4f}** (the meeting's 0.014 is the RMS).",
        f"- |cos| 95th / 99th / 99.9th percentile: {an['abs_q95']:.4f} / {an['abs_q99']:.4f} / {an['abs_q999']:.4f}.",
        f"- Max of |cos| over 64 independent layers (what a \"max (L)\" column reports): median {an['max64_abs_median']:.4f}, 95th percentile {an['max64_abs_q95']:.4f}.",
        f"- Mean of cos over the 24 window layers (L40–63), if layers were independent: SD {an['window24_mean_sd']:.4f}.",
        "",
        "z below = cos / RMS, i.e. cos in units of the random-pair SD.",
        "",
    ]

    def table(pairs, title, note=""):
        nonlocal lines
        lines += [f"## {title}", ""] + ([note, ""] if note else [])
        lines.append("| pair | " + " | ".join(f"L{l}" for l in LAYERS) + " | mean L40–63 | z (mean L40–63) | max |cos| (L) over 1..64 |")
        lines.append("|---|" + "---|" * (len(LAYERS) + 3))
        res = {}
        for a, b in pairs:
            c = cos(a, b)
            w = float(np.mean([c[l] for l in WINDOW]))
            idx = int(np.argmax(np.abs(c[1:]))) + 1
            res[f"{a} | {b}"] = c.tolist()
            lines.append(f"| {a} vs {b} | " + " | ".join(f"{c[l]:+.3f}" for l in LAYERS) + f" | {w:+.3f} | {w / an['rms']:+.1f} | {c[idx]:+.3f} (L{idx}) |")
        lines.append("")
        return res

    allres = {}
    hack = ["D_TV", "D_MBPP", "D_GR", "R1 (attempt_vs_A, completion_last)"]
    allres["hack_vs_hack"] = table(list(itertools.combinations(hack, 2)), "2. Hack directions against each other")
    allres["random"] = table(
        [("random_s1", "random_s2")] + [(h, r) for h in hack[:3] for r in ["random_s1", "random_s2"]],
        "3. Stored random control directions",
        "Empirical check of the analytic baseline; the hack directions against random directions should sit inside it.",
    )
    unrelated = ["concept (covert vs simple)", "env: TV − MBPP (non-hack means)", "env: TV − GR (non-hack means)", "env: MBPP − GR (non-hack means)", "mean residual (anisotropy axis)"]
    allres["unrelated"] = table(
        [(h, u) for h in hack for u in unrelated],
        "4. Hack directions against activation-based unrelated directions",
        "Environment-identity directions (difference of two environments' non-hack class means) and the concept direction live in the model's actual activation geometry. "
        "If a hack direction's cosine with these is as large as with another hack direction, the hack-vs-hack cosine is not evidence of a shared hacking component. "
        "The env directions are not fully unrelated to the hack directions by construction (they share each environment's non-hack mean), so treat them as an upper reference, and the concept direction as the cleaner one. "
        "Spanish/French and refusal directions (the mentor's suggestion) need a GPU pass.",
    )
    allres["unrelated_vs_unrelated"] = table(list(itertools.combinations(unrelated[:4], 2)), "5. Unrelated directions against each other (typical cosine of unrelated activation directions)")

    # same-behaviour floors
    lines += ["## 6. Same-behaviour floors (a direction re-extracted from less or other data)", "", "| direction | variant | " + " | ".join(f"L{l}" for l in LAYERS) + " | mean L40–63 |", "|---|---|" + "---|" * (len(LAYERS) + 1)]
    fl = {}
    for base, vs in floors.items():
        for name, sub in vs.items():
            p = s4 / sub / "directions" / f"{fname[base]}__cot_last.safetensors"
            if not p.exists():
                continue
            u = unit(load_file(str(p))["direction"].astype(np.float64))
            c = (U[base] * u).sum(-1)
            fl[f"{base} | {name}"] = c.tolist()
            lines.append(f"| {base} | {name} | " + " | ".join(f"{c[l]:+.3f}" for l in LAYERS) + f" | {np.mean([c[l] for l in WINDOW]):+.3f} |")
    lines.append("")
    allres["floors"] = fl

    # pooled algebra
    c_mg = cos("D_MBPP", "D_GR")
    pred = np.sqrt((1 + c_mg) / 2)
    obs = cos("D_MBPP+GR (X2)", "D_MBPP")
    lines += [
        "## 7. Pooled directions: member cosines are fixed by construction",
        "",
        "pool = normalise(u_A + u_B) ⇒ cos(pool, u_A) = sqrt((1 + cos(u_A, u_B)) / 2). With near-orthogonal members that is ≈ 0.71, so the 0.6–0.76 member cosines in the stage-7 table say nothing about shared structure.",
        "",
        "| layer | cos(D_MBPP, D_GR) | predicted cos(X2, D_MBPP) | observed |",
        "|---|---|---|---|",
    ] + [f"| L{l} | {c_mg[l]:+.3f} | {pred[l]:.3f} | {obs[l]:.3f} |" for l in LAYERS] + [""]

    (out / "results.md").write_text("\n".join(lines) + "\n")
    (out / "results.json").write_text(json.dumps({"analytic": an, **allres}, indent=1))
    print(f"wrote {out}/results.md")


if __name__ == "__main__":
    main()
